export function translateMessage(message: string): string {
  const sessionImageLimit = message.match(/^Cada sessão pode ter no máximo (\d+) imagens\.$/)
  if (sessionImageLimit) {
    return i18n.t('Cada sessão pode ter no máximo {{count}} imagens.', {
      count: Number(sessionImageLimit[1]),
    })
  }

  const imageStatus = message.match(/^Não foi possível carregar as imagens do jogo \(HTTP (\d+)\)\.$/)
  if (imageStatus) {
    return i18n.t('Não foi possível carregar as imagens do jogo (HTTP {{status}}).', {
      status: imageStatus[1],
    })
  }

  return i18n.t(message)
}

export function formatNumber(
  value: number,
  options: Intl.NumberFormatOptions = {},
): string {
  return new Intl.NumberFormat(i18n.language, options).format(value)
}

export function formatDate(value: string): string {
  const date = new Date(`${value}T00:00:00`)
  if (Number.isNaN(date.getTime())) return value
  return new Intl.DateTimeFormat(i18n.language, { dateStyle: 'medium' }).format(date)
}

